#!/usr/bin/env python3
"""fabdocs.py VDIR OUTDIR -> drawings.pdf, bom.csv, bom_quote.pdf, build_steps.pdf, sanity.txt, quote.json
Reads VDIR/parts.json, shop_drawing.png, hero.png, steps/ (from build_replay), OUTDIR/nest/nest.json, OUTDIR/gcode/*.json.
All prices/labor are ESTIMATES. All drawings must be checked by a qualified person before fabrication."""
import sys,os,json,csv,glob,matplotlib
matplotlib.use("Agg"); import matplotlib.pyplot as plt
from reportlab.lib.pagesizes import letter,landscape
from reportlab.lib.units import inch
from reportlab.pdfgen import canvas
from reportlab.lib.utils import ImageReader
B=os.path.dirname(os.path.abspath(__file__)); V,O=sys.argv[1],sys.argv[2]; os.makedirs(O,exist_ok=True)
d=json.load(open(f"{V}/parts.json")); P=d["params"]; M=json.load(open(f"{B}/machines.json")); shop=M.get("shop",{})
title=P.get("title",P["kind"].replace("_"," ").title()); PW,PH=landscape(letter)
def header(c,t,sub=""):
    c.setFont("Helvetica-Bold",15); c.drawString(0.5*inch,PH-0.6*inch,t); c.setFont("Helvetica",8)
    c.drawString(0.5*inch,PH-0.8*inch,sub or f"{title} · units: {P.get('units','in')} · generated by Sketch · CHECK ALL DIMENSIONS BEFORE CUTTING")
    c.rect(PW-3.3*inch,0.3*inch,3.0*inch,0.55*inch); c.drawString(PW-3.25*inch,0.68*inch,f"{title[:42]}"); c.drawString(PW-3.25*inch,0.45*inch,"Drawn: Sketch   Checked: ______   Date: ______")
def img_page(c,path,t):
    header(c,t); im=ImageReader(path); iw,ih=im.getSize(); s=min((PW-1*inch)/iw,(PH-1.9*inch)/ih)
    c.drawImage(im,0.5*inch,1.0*inch,iw*s,ih*s); c.showPage()
# ---- flat part drawings
def flat_png(f,path):
    fig,ax=plt.subplots(figsize=(10,6)); ax.set_aspect("equal"); ax.axis("off"); dims=[]
    if f["shape"] in("circle","annulus"):
        ax.add_patch(plt.Circle((0,0),f["r"],fill=False,lw=2)); W=H=2*f["r"]; ox=oy=-f["r"]
        ax.annotate("",(-f["r"],f["r"]*1.15),(f["r"],f["r"]*1.15),arrowprops=dict(arrowstyle="<->",color="tab:blue")); ax.text(0,f["r"]*1.18,f'Ø{2*f["r"]:.3f}',ha="center",color="tab:blue")
        if f["shape"]=="annulus":
            ax.add_patch(plt.Circle((0,0),f["ri"],fill=False,lw=2)); ax.text(0,0,f'ID Ø{2*f["ri"]:.3f}',ha="center",color="tab:blue")
    elif f["shape"]=="poly":
        W,H=f["w"],f["h"]; ox=oy=0; ax.add_patch(plt.Polygon(f["outer"],closed=True,fill=False,lw=2))
        for ip in f.get("inner_poly",[]): ax.add_patch(plt.Polygon(ip,closed=True,fill=False,lw=1.5))
        for k,pk in enumerate(f.get("pockets",[])):
            ax.add_patch(plt.Polygon(pk["poly"],closed=True,color="orange",alpha=0.45)); xs=[q[0] for q in pk["poly"]]; ys=[q[1] for q in pk["poly"]]
            ax.text((min(xs)+max(xs))/2,(min(ys)+max(ys))/2,f'P{k+1}\n{max(xs)-min(xs):.3f} x {max(ys)-min(ys):.3f}\n{pk["depth"]:.3f} deep',ha="center",va="center",fontsize=7)
            ax.text(min(xs),min(ys)-0.04*max(W,H),f'@ X{min(xs):.3f} Y{min(ys):.3f}',fontsize=6,color="0.3")
        ax.annotate("",(0,H*1.12),(W,H*1.12),arrowprops=dict(arrowstyle="<->",color="tab:blue")); ax.text(W/2,H*1.14,f'{W:.3f}',ha="center",color="tab:blue")
        ax.annotate("",(W*1.03,0),(W*1.03,H),arrowprops=dict(arrowstyle="<->",color="tab:blue")); ax.text(W*1.04,H/2,f'{H:.3f}',va="center",color="tab:blue")
    else:
        W,H=f["w"],f["h"]; ox=oy=0; ax.add_patch(plt.Rectangle((0,0),W,H,fill=False,lw=2))
        ax.annotate("",(0,H*1.12),(W,H*1.12),arrowprops=dict(arrowstyle="<->",color="tab:blue")); ax.text(W/2,H*1.14,f'{W:.3f}',ha="center",color="tab:blue")
        ax.annotate("",(W*1.03,0),(W*1.03,H),arrowprops=dict(arrowstyle="<->",color="tab:blue")); ax.text(W*1.04,H/2,f'{H:.3f}',va="center",color="tab:blue")
    hs=f.get("holes",[])
    for i,(x,y,r) in enumerate(hs): ax.add_patch(plt.Circle((x,y),r,fill=False,color="k")); ax.text(x,y+r*1.3,str(i+1),fontsize=6,ha="center")
    if hs:
        dia=sorted(set(round(2*r,3) for *_,r in hs)); ax.text(ox,oy-0.12*max(W,H),"; ".join(f'{sum(1 for *_,r in hs if round(2*r,3)==q)}x Ø{q}' for q in dia)+" thru",fontsize=10)
    ax.margins(0.18); fig.savefig(path,dpi=90,bbox_inches="tight"); plt.close(fig)
    return hs
c=canvas.Canvas(f"{O}/drawings.pdf",pagesize=landscape(letter))
if os.path.exists(f"{V}/hero.png"): img_page(c,f"{V}/hero.png","Concept render (sales picture, not to scale)")
if os.path.exists(f"{V}/shop_drawing.png"): img_page(c,f"{V}/shop_drawing.png","General arrangement and cut list")
if os.path.exists(f"{V}/drawing_2.png"): img_page(c,f"{V}/drawing_2.png","Cut / part list (continued)")
for f in d["flats"]:
    pth=f"{O}/_flat_{f['name']}.png"; hs=flat_png(f,pth); header(c,f"Flat part: {f['name']}",f"{f.get('thickness','?')}\" {f.get('material','')} · {f.get('roll','flat')} · DXF: dxf/{f['name']}.dxf · CHECK BEFORE CUTTING")
    im=ImageReader(pth); iw,ih=im.getSize(); s=min((PW-4.5*inch)/iw,(PH-1.9*inch)/ih); c.drawImage(im,0.5*inch,1.0*inch,iw*s,ih*s)
    c.setFont("Helvetica-Bold",9); c.drawString(PW-3.8*inch,PH-1.2*inch,"Hole table (from part origin)"); c.setFont("Courier",7.5)
    for i,(x,y,r) in enumerate(hs[:40]): c.drawString(PW-3.8*inch,PH-1.4*inch-i*10,f"{i+1:>2}  X{x:8.3f} Y{y:8.3f}  Ø{2*r:.3f}")
    c.showPage(); os.remove(pth)
# weld schedule with a simple fillet-weld symbol
if d.get("welds"):
    header(c,"Weld schedule")
    def sym(x,y,txt):
        c.setLineWidth(1); c.line(x,y,x+90,y); c.line(x,y,x-15,y-15)   # reference line + arrow leader
        c.line(x-15,y-15,x-11,y-9); c.line(x-15,y-15,x-8,y-13)
        c.line(x+35,y,x+35,y-12); c.line(x+35,y-12,x+47,y)   # fillet triangle below line = arrow side
        c.setFont("Helvetica",8); c.drawString(x+95,y-3,txt)
    y=PH-1.3*inch
    for w in d["welds"]:
        sym(0.9*inch,y,f'{w["part"]}: {w["weld"]}  (~{w["weld_in"]}" of weld)'); y-=26
        if y<1.2*inch: c.showPage(); header(c,"Weld schedule (cont.)"); y=PH-1.3*inch
    c.setFont("Helvetica-Oblique",8); c.drawString(0.9*inch,0.95*inch,"Symbols simplified (AWS A2.4 style: fillet on arrow side). Confirm sizes with your engineer/WPS.")
    c.showPage()
c.save()
# ---- sanity checks
S=[]; tw=d["total_weight_lb"]
_pg=0.0
try:
    for _pp in json.load(open(f"{O}/print/print.json")).get("parts",[]):
        for _pc in _pp.get("pieces",[]): _pg+=float(_pc.get("grams") or 0)
except Exception: pass
if _pg and tw<0.05: tw=_pg/453.6   # older parts.json had no print weight (showed ~0 lb); newer spec_build already includes it
else: _pg=0
S.append(f"Total weight ~{tw:.1f} lb"+(f" (incl. ~{_pg:.0f} g printed parts)" if _pg else "")+": "+("one person OK" if tw<50 else "two-person lift" if tw<150 else "use a hoist, forklift or cart"))
for r in d["cutlist"]:
    if not str(r.get("weight","")).strip(): continue
    w=float(r["weight"].split()[0])/max(1,r["qty"])
    if w>50: S.append(f"Part {r['mark']} {r['part']} weighs ~{w:.0f} lb each: plan lifting/handling")
pl=M.get("plasma",{})
for f in d["flats"]:
    t=f.get("thickness",0); W=f.get("w",2*f.get("r",0)); H=f.get("h",2*f.get("r",0))
    for x,y,r in f.get("holes",[]):
        if 2*r<pl.get("min_hole_ratio",1)*t: S.append(f"{f['name']}: Ø{2*r:.3f} hole < plasma minimum ({pl.get('min_hole_ratio',1)}x thickness) -> drill")
        if f["shape"].startswith("rect"):
            e=min(x-r,W-x-r,y-r,H-y-r)
            if e<max(t,1.5*r)-1e-6: S.append(f"{f['name']}: hole at ({x:.2f},{y:.2f}) only {e:.2f}\" from edge (< {max(t,1.5*r):.2f}\" rule of thumb)")
if d.get("domain")=="wood":
    for f in d["flats"]:
        if "shelf" in f["name"].lower() and max(f["w"],f["h"])>32 and f.get("thickness",1)<=0.75:
            S.append(f"{f['name']}: {max(f['w'],f['h']):.1f}\" span in {f.get('thickness')}\" plywood will sag under heavy loads (books): add a centre divider, a hardwood front edge strip, or go to 1\"")
nj=os.path.join(O,"nest","nest.json")
if os.path.exists(nj):
    for n in json.load(open(nj))["notes"]: S.append("Nesting: "+n)
for g in sorted(glob.glob(f"{O}/gcode/*.json")):
    j=json.load(open(g)); [S.append(f"{os.path.basename(g)}: {w}") for w in j["warnings"]]
S.append("G-code and templates are STARTING POINTS: verify in simulator, dry-run, and test-cut on scrap before production.")
open(f"{O}/sanity.txt","w").write("SANITY CHECKS (automatic, not a substitute for a qualified review)\n"+"\n".join("- "+s for s in S)+"\n")
# ---- quote
cut_min=sum(json.load(open(g))["est_min"] for g in glob.glob(f"{O}/gcode*/*plasma.json")+glob.glob(f"{O}/gcode*/*router.json"))
weld_in=sum(w.get("weld_in",0) for w in d.get("welds",[])); nparts=sum(r["qty"] for r in d["cutlist"] if r.get("mark")!="HW")
hrs=dict(cutting=round(cut_min/60+0.25*len(glob.glob(f'{O}/gcode/*plasma.nc')),2),saw_cope=round(0.08*sum(r["qty"] for r in d["cutlist"] if "pipe" in r["material"] or "tube" in r["material"] or "cedar" in r["material"]),2),
         fit_tack=round(shop.get("fit_hours_per_part",0.15)*nparts,2),weld=round(weld_in/shop.get("weld_ipm",6)/60*2.5,2),finish=shop.get("finish_hours",1.0))
dom=d.get("domain")
if dom=="print": hrs=dict(post_process=0.15)
elif dom=="wood": hrs=dict(cutting=hrs["cutting"],saw=round(0.05*nparts,2),assembly_glue=round(0.1*nparts,2),sand_finish=round(0.5+0.1*nparts,2))
mat=d["est_cost"]; pj=f"{O}/print/print.json"
if os.path.exists(pj):   # printed parts: filament cost + ~$0.50/h machine time + 0.1 h setup per plate
    import re as _re
    for r_ in json.load(open(pj))["parts"]:
        for pc in r_["pieces"]:
            mat+=float(pc.get("cost") or 0); t_=pc.get("time") or ""; hh=sum(int(n)*{"d":24,"h":1,"m":1/60,"s":1/3600}[u] for n,u in _re.findall(r"(\d+)([dhms])",t_))
            hrs["printing_machine"]=round(hrs.get("printing_machine",0)+hh,2); hrs["print_setup"]=round(hrs.get("print_setup",0)+0.1*(pc.get("share_of_plate",1)),2)
pm=hrs.pop("printing_machine",0); lab=sum(hrs.values())*shop.get("labor_rate",75)+pm*0.5; mat=round(mat,2); sub=lab+mat; price=sub*(1+shop.get("margin_pct",25)/100)
SRC_=[dict(line=f'{r_["part"]} ({r_["material"]}) x{r_["qty"]}',usd=r_.get("cost_usd"),source=r_.get("cost_src","?")) for r_ in d["cutlist"] if r_.get("mark")!="HW"]
if os.path.exists(pj):
    for r_ in json.load(open(pj))["parts"]:
        for pc in r_["pieces"]: SRC_.append(dict(line=f'filament {pc["name"]}',usd=float(pc.get("cost") or 0),source="PrusaSlicer (print.json)"))
SRC_.append(dict(line="labor",usd=round(lab),source=f'machines.json shop labor_rate {shop.get("labor_rate",75)}/h; hours: cut minutes from gcode*/*.json (nest + G-code), other hours per-part rates in machines.json shop'))
Q=dict(sources=SRC_,material_est=round(mat,2),printer_hours=pm,labor_hours=hrs,labor_est=round(lab),subtotal=round(sub),margin_pct=shop.get("margin_pct",25),price_est=round(price),note="ESTIMATE ONLY: edit bin/prices.json and machines.json 'shop'")
json.dump(Q,open(f"{O}/quote.json","w"),indent=1)
# ---- shopping list: everything you buy (store-bought stock, hardware, sheet goods/lumber/metal to cut from)
with open(f"{O}/shopping_list.csv","w",newline="") as fh:
    w=csv.writer(fh); w.writerow(["item","qty","size","why","est. cost"])
    for r_ in d["cutlist"]:
        if r_.get("stock")=="print": continue
        why="hardware" if r_.get("mark")=="HW" else ("buy as-is" if r_.get("stock")=="buy" else f'raw stock for {", ".join(r_.get("names",[]))}')
        w.writerow([r_["material"] if r_.get("mark")=="HW" or r_.get("stock")=="buy" else f'{r_["material"]} ({r_["part"]})',r_["qty"],r_.get("length",""),why,r_.get("est. cost","")])
# ---- BOM csv + pdf
with open(f"{O}/bom.csv","w",newline="") as fh:
    cols=["mark","part","material","qty","length","weight","est. cost","notes"]; w=csv.DictWriter(fh,fieldnames=cols,extrasaction="ignore"); w.writeheader(); [w.writerow(r) for r in d["cutlist"]]
c=canvas.Canvas(f"{O}/bom_quote.pdf",pagesize=landscape(letter)); header(c,"Bill of materials, cut list and quote (estimates)")
y=PH-1.25*inch; c.setFont("Helvetica-Bold",8); X=[0.5,0.95,2.6,4.6,5.0,6.6,7.4,8.2]
for x,h in zip(X,cols): c.drawString(x*inch,y,h.upper())
c.setFont("Helvetica",8)
for r in d["cutlist"]:
    y-=13
    for x,h in zip(X,cols): c.drawString(x*inch,y,str(r.get(h,""))[:38 if h=="notes" else 30])
y-=24; c.setFont("Helvetica-Bold",10); c.drawString(0.5*inch,y,f"Total weight ~{tw:.1f} lb    Material ~${mat}"); y-=20
c.setFont("Helvetica",9)
for k,v in hrs.items(): c.drawString(0.7*inch,y,f"{k.replace('_',' ')}: {v} h"); y-=12
c.setFont("Helvetica-Bold",10); y-=6
c.drawString(0.5*inch,y,f"Labor ~{sum(hrs.values()):.1f} h x ${shop.get('labor_rate',75)}/h = ~${lab:.0f}   Subtotal ~${sub:.0f}   +{shop.get('margin_pct',25)}% margin  =>  QUOTE ~${price:.0f}")
c.setFont("Helvetica-Oblique",8); c.drawString(0.5*inch,y-16,"All prices and hours are rough estimates from bin/prices.json and machines.json; confirm with your supplier and shop rates.")
c.save()
# ---- build steps
c=canvas.Canvas(f"{O}/build_steps.pdf",pagesize=landscape(letter)); sd=f"{V}/steps"
caps=json.load(open(f"{sd}/captions.json")) if os.path.exists(f"{sd}/captions.json") else []
header(c,"Build steps",f"{title} · follow with the cut list (bom_quote.pdf), drawings.pdf"+(", cope_templates.pdf" if d.get("joints") else "")+" · watch replay.mp4 for the animated version")
c.setFont("Helvetica",10); y=PH-1.3*inch
pre=["Read sanity.txt. Verify every dimension on drawings.pdf.","Cut parts: flat parts from nest/ DXF or gcode/ (test-cut first); saw stock per cut list."]
if d.get("joints"): pre.append("Cope pipe ends with cope_templates.pdf (print at 100%), test-fit, grind to fit.")
for i,s in enumerate(pre): c.drawString(0.6*inch,y,f"{i+1}. {s}"); y-=15
c.showPage()
wl={w["part"]:w["weld"] for w in d.get("welds",[])}
for i,cap in enumerate(caps):
    header(c,f"Step {i+1} of {len(caps)}: {cap}")
    im=f"{sd}/{i+1:02d}.png"
    if os.path.exists(im): c.drawImage(ImageReader(im),0.5*inch,1.1*inch,5.6*inch,5.6*inch)
    c.setFont("Helvetica",10); yy=PH-1.4*inch
    tips={"Applying the finish":"Degrease, prep, and apply the finish per the product label.","Lighting the fire":"Cure the paint with a small first fire."}
    c.drawString(6.4*inch,yy,tips.get(cap,"Fit, check square/level, tack. Weld out only after the full assembly checks true.")); yy-=18
    rel=[f"{k}: {v}" for k,v in wl.items() if cap.split()[-1][:4].lower() in k.lower() or any(w in cap.lower() for w in [k.rstrip('0123456789-X Y').lower()])]
    for t in rel[:8]: c.drawString(6.4*inch,yy,"• "+t[:60]); yy-=13
    c.showPage()
c.save(); print("docs ->",O)
