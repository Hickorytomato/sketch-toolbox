def _diff(old,new,oldp,newp):
    ch=[]
    ov={k:(v.get("v") if isinstance(v,dict) else v) for k,v in old.get("values",{}).items()}; nv={k:(v.get("v") if isinstance(v,dict) else v) for k,v in new.get("values",{}).items()}
    for k in sorted(set(ov)|set(nv)):
        if ov.get(k)!=nv.get(k): ch.append(f"{k} {ov.get(k,'(none)')} -> {nv.get(k,'(removed)')}")
    on={p_["name"] for p_ in old.get("parts",[])}; nn={p_["name"] for p_ in new.get("parts",[])}
    ch+=[f"added part {x}" for x in sorted(nn-on)]+[f"removed part {x}" for x in sorted(on-nn)]
    oc={(r_["mark"],r_["part"]):(r_.get("length"),r_["qty"],r_["material"]) for r_ in oldp.get("cutlist",[]) if r_.get("mark")!="HW"}
    nc={(r_["mark"],r_["part"]):(r_.get("length"),r_["qty"],r_["material"]) for r_ in newp.get("cutlist",[]) if r_.get("mark")!="HW"}
    for k in sorted(set(oc)&set(nc)):
        if oc[k]!=nc[k]: ch.append(f"{k[0]} {k[1]}: "+", ".join(f"{a_} -> {b_}" for a_,b_ in zip(oc[k],nc[k]) if a_!=b_))
    if json.dumps(old.get("joints",[]),sort_keys=True)!=json.dumps(new.get("joints",[]),sort_keys=True): ch.append("joints changed")
    ow=[w_.get("weld") for w_ in oldp.get("welds",[])]; nw=[w_.get("weld") for w_ in newp.get("welds",[])]
    if ow!=nw: ch.append("weld schedule changed")
    return ch
